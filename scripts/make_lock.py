"""Regenerate backend/requirements.lock: install requirements.txt into a CLEAN virtualenv and freeze exactly what resolved.

    python scripts/make_lock.py

Commit the result so every deployment installs identical versions (no surprise upgrades on Render).
"""
import subprocess
import sys
import tempfile
from pathlib import Path

backend = Path(__file__).resolve().parents[1] / "backend"
with tempfile.TemporaryDirectory() as tmp:
    venv = Path(tmp) / "venv"
    subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
    py = venv / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
    subprocess.run([str(py), "-m", "pip", "install", "-q", "--upgrade", "pip"], check=True)
    subprocess.run([str(py), "-m", "pip", "install", "-q", "-r", str(backend / "requirements.txt")], check=True)
    frozen = subprocess.run([str(py), "-m", "pip", "freeze", "--exclude", "pip"], check=True, capture_output=True, text=True).stdout
(backend / "requirements.lock").write_text("# Generated by scripts/make_lock.py. Do not edit by hand.\n" + frozen, encoding="utf-8")
print(f"wrote {backend / 'requirements.lock'} ({len(frozen.splitlines())} packages)")
